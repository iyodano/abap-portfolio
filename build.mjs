const PAGES = ['quest.html'];
// Cache busting: assets/…css|js?v=<content hash>, so phones and GitHub Pages never serve an old copy
const bust = html => html.replace(/((?:src|href)=")(assets\/[^"?]+\.(?:css|js))(?:\?v=\w+)?"/g, (m, pre, path) => {
  const file = join(ROOT, path);
  if (!existsSync(file)) return m;
  return `${pre}${path}?v=${createHash('sha1').update(readFileSync(file)).digest('hex').slice(0, 8)}"`;
});

function build() {
  const html = readFileSync(INDEX, 'utf8');
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new BuildError(`index.html: the markers ${START.slice(0, 22)}… and ${END} were not found`);
  const icons = new Set([...html.matchAll(/<symbol id="i-([\w-]+)"/g)].map(m => m[1]));
  const files = readdirSync(DIR).filter(f => f.endsWith('.md') && !f.startsWith('_')).sort();
  const projects = files.map(f => readProject(join(DIR, f), icons)).filter(Boolean);
  const seen = new Map();
  for (const p of projects) {
    if (seen.has(p.meta.id)) throw new BuildError(`id "${p.meta.id}" is used by ${seen.get(p.meta.id)} and ${p.file}`);
    seen.set(p.meta.id, p.file);
  }
  const byOrder = (x, y) => x.order - y.order || x.file.localeCompare(y.file);
  const main = projects.filter(p => p.meta.place === 'main').sort(byOrder);
  const more = projects.filter(p => p.meta.place === 'more').sort(byOrder);
  const block = `${START}\n${main.map(renderMain).join('\n\n')}\n${renderMoreCard(more)}\n      ${END}`;
  let next = html.slice(0, a) + block + html.slice(b + END.length);
  next = bust(next);
  if (next !== html) writeFileSync(INDEX, next);
  // The other pages (quest.html) only get their asset versions refreshed
  for (const page of PAGES) {
    const file = join(ROOT, page);
    if (!existsSync(file)) continue;
    const src = readFileSync(file, 'utf8'), out = bust(src);
    if (out !== src) { writeFileSync(file, out); console.log(`✓ asset versions updated → ${page}`); }
  }
  const stamp = new Date().toLocaleTimeString();
  console.log(`✓ ${stamp}  ${main.length} on the front page, ${more.length} in "More projects"${next === html ? ' (no changes)' : ' → index.html'}`);
}

function run() {
  try { build(); return true; } catch (e) {
    if (e instanceof BuildError) { console.error(`✗ ${e.message}`); return false; }
    throw e;
  }
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === 'new') {
  if (!arg || !/^[a-z0-9-]+$/.test(arg)) { console.error('Usage: node build.mjs new my-project-id   (lower-case letters, digits and "-")'); process.exit(1); }
  const target = join(DIR, `${arg}.md`);
  if (existsSync(target)) { console.error(`✗ ${target} already exists`); process.exit(1); }
  writeFileSync(target, readFileSync(TEMPLATE, 'utf8').replace(/^id:.*$/m, `id: ${arg}`).replace(/^draft:.*$/m, 'draft: yes'));
  console.log(`✓ Created content/projects/${arg}.md (as a draft: it is not published until you remove "draft: yes")`);
} else if (cmd === '--watch' || cmd === 'watch') {
  run();
  console.log('Watching content/projects/ … (Ctrl+C to stop)');
  let timer = null;
  watch(DIR, () => { clearTimeout(timer); timer = setTimeout(run, 150); });
} else if (!cmd) {
  process.exit(run() ? 0 : 1);
} else {
  console.error(`Unknown option "${cmd}". Use: node build.mjs | node build.mjs --watch | node build.mjs new <id>`);
  process.exit(1);
}
