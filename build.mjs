/* ---------------------------------------------------------------- small helpers */
class BuildError extends Error {}
const fail = (file, msg) => { throw new BuildError(`${file}: ${msg}`); };
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const attr = s => esc(s).replace(/"/g, '&quot;');
const L = (en, es) => `<span lang="en">${en}</span><span lang="es">${es}</span>`;

// "English | Español" → [en, es]; a value without " | " is the same in both languages
const bi = v => {
  const i = String(v ?? '').indexOf(' | ');
  return i < 0 ? [String(v ?? '').trim(), String(v ?? '').trim()] : [v.slice(0, i).trim(), v.slice(i + 3).trim()];
};

// Inline Markdown: `code`, **bold**, *italic*, [text](url). A few inline HTML tags are allowed as they are.
function inline(s) {
  const codes = [];
  s = String(s).replace(/`([^`]+)`/g, (_, c) => { codes.push(`<code>${esc(c)}</code>`); return `\u0000${codes.length - 1}\u0000`; });
  s = s.replace(/&(?!#?\w+;)/g, '&amp;')
       .replace(/<(?!\/?(?:b|i|em|strong|code|br|a|span|small|sup|sub|kbd|u|mark)\b)/g, '&lt;')
       .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
       .replace(/(^|[^*\w])\*(?=\S)(.+?)(?<=\S)\*(?!\w)/g, '$1<i>$2</i>')
       .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, n) => codes[n]);
}

// Block Markdown: paragraphs, "- " lists, "1. " lists and raw HTML blocks (a line starting with "<").
function blocks(md) {
  const lines = md.replace(/\r/g, '').split('\n');
  const out = [];
  const isUl = l => /^\s*[-*]\s+/.test(l);
  const isOl = l => /^\s*\d+[.)]\s+/.test(l);
  let i = 0;
  while (i < lines.length) {
    if (!lines[i].trim()) { i++; continue; }
    if (isUl(lines[i]) || isOl(lines[i])) {
      const ordered = isOl(lines[i]);
      const test = ordered ? isOl : isUl;
      const items = [];
      while (i < lines.length) {
        if (test(lines[i])) items.push(lines[i].replace(/^\s*(?:[-*]|\d+[.)])\s+/, ''));
        else if (lines[i].trim() && /^\s/.test(lines[i]) && items.length) items[items.length - 1] += ' ' + lines[i].trim();
        else if (!lines[i].trim() && i + 1 < lines.length && test(lines[i + 1])) { /* blank line between items */ }
        else break;
        i++;
      }
      const tag = ordered ? 'ol' : 'ul';
      out.push(`<${tag}>${items.map(t => `\n  <li>${inline(t)}</li>`).join('')}\n</${tag}>`);
    } else if (/^\s*</.test(lines[i])) {
      const raw = [];
      while (i < lines.length && lines[i].trim()) raw.push(lines[i++]);
      out.push(raw.join('\n'));
    } else {
      const para = [];
      while (i < lines.length && lines[i].trim() && !isUl(lines[i]) && !isOl(lines[i])) para.push(lines[i++].trim());
      out.push(`<p>${inline(para.join(' '))}</p>`);
    }
  }
  return out.join('\n');
}

/* ---------------------------------------------------------------- reading a project file */
function frontMatter(text, file) {
  const m = text.replace(/\r/g, '').match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) fail(file, 'the file must start with a "---" block (see content/_template.md)');
  const meta = {};
  let listKey = null;
  for (const raw of m[1].split('\n')) {
    if (!raw.trim() || /^\s*#/.test(raw)) continue;
    const line = raw.replace(/\s{2,}#.*$/, '');            // "  # comment" at the end of a line
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && listKey) { meta[listKey].push(item[1].trim()); continue; }
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) fail(file, `cannot read this line of the --- block: "${raw.trim()}"`);
    const [, key, value] = kv;
    if (value.trim() === '') { meta[key] = []; listKey = key; } else { meta[key] = value.trim(); listKey = null; }
  }
  for (const k of Object.keys(meta)) if (Array.isArray(meta[k]) && !meta[k].length) meta[k] = '';   // "status:" left empty
  return { meta, body: m[2].replace(/<!--[\s\S]*?-->/g, '') };                                     // <!-- notes to self --> are ignored
}

// "# English", "# Español", "# Code" → { en, es, code }
function topSections(body, file) {
  const out = {};
  let key = null;
  for (const line of body.split('\n')) {
    const h = line.match(/^#\s+(.+?)\s*$/);
    if (h) {
      const name = h[1].toLowerCase();
      key = /^(english|en|inglés|ingles)$/.test(name) ? 'en'
          : /^(español|espanol|es|spanish|castellano)$/.test(name) ? 'es'
          : /^(code|código|codigo)$/.test(name) ? 'code' : fail(file, `unknown section "# ${h[1]}" (use # English, # Español or # Code)`);
      out[key] = [];
      continue;
    }
    if (key) out[key].push(line);
  }
  for (const k of Object.keys(out)) out[k] = out[k].join('\n');
  return out;
}

// One language: "> summary" lines, then "## Heading {modifier}" sections
function story(text, file, lang) {
  if (!text || !text.trim()) fail(file, `the "# ${lang === 'en' ? 'English' : 'Español'}" section is missing or empty`);
  const lines = text.split('\n');
  const summary = [];
  let i = 0;
  while (i < lines.length && (!lines[i].trim() || /^>/.test(lines[i]))) {
    if (/^>/.test(lines[i])) summary.push(lines[i].replace(/^>\s?/, '').trim());
    i++;
  }
  const sections = [];
  let cur = null;
  for (; i < lines.length; i++) {
    const h = lines[i].match(/^##\s+(.+?)\s*(?:\{([\w\s]+)\})?\s*$/);
    if (h) {
      const mods = (h[2] || '').trim().split(/\s+/).filter(Boolean);
      const bad = mods.find(x => ![...BOXES, 'flow', 'half'].includes(x));
      if (bad) fail(file, `unknown modifier {${bad}} in "## ${h[1]}" (use result, lesson, improve, flow or half)`);
      cur = { title: h[1], mods, lines: [] };
      sections.push(cur);
    } else if (cur) cur.lines.push(lines[i]);
    else if (lines[i].trim()) { cur = { title: '', mods: [], lines: [lines[i]] }; sections.push(cur); }
  }
  return { summary: summary.join(' '), sections };
}

function renderSection(s) {
  const box = BOXES.find(b => s.mods.includes(b));
  const body = s.mods.includes('flow')
    ? '<div class="pills">' + s.lines.join(' ').split(/\s*->\s*|\s*→\s*/).filter(x => x.trim()).map(x => `<span class="chip">${inline(x.trim())}</span>`).join('') + '</div>'
    : blocks(s.lines.join('\n'));
  const h = s.title ? `<h4>${inline(s.title)}</h4>` : '';
  return `<div${box ? ` class="${box}"` : ''}>${h}${body}</div>`;
}

// Sections → HTML, pairing consecutive {half} sections side by side. Split before the first box (where the code goes).
function renderStory(sections) {
  const firstBox = sections.findIndex(s => BOXES.some(b => s.mods.includes(b)));
  const parts = firstBox < 0 ? [sections, []] : [sections.slice(0, firstBox), sections.slice(firstBox)];
  return parts.map(list => {
    const out = [];
    for (let i = 0; i < list.length; i++) {
      const a = list[i], b = list[i + 1];
      if (a.mods.includes('half') && b && b.mods.includes('half')) {
        const boxes = BOXES.some(x => a.mods.includes(x)) && BOXES.some(x => b.mods.includes(x));
        out.push(`<div class="${boxes ? 'callouts' : 'cols'}">\n${renderSection(a)}\n${renderSection(b)}\n</div>`);
        i++;
      } else out.push(renderSection(a));
    }
    return out.join('\n');
  });
}

/* ---------------------------------------------------------------- the code panel */
const MARK = /\s*(?:\/\/\s?(\d+)|⟦(\d+)⟧)\s*$/;   // "//3" at the end of a code line links it to note 3

function parseNotes(lines, file) {
  const notes = [];
  for (const line of lines) {
    const m = line.match(/^\s*(\d+)[.)]\s+(.*)$/);
    if (m) { notes.push(m[2]); continue; }
    if (line.trim() && notes.length) notes[notes.length - 1] += '\n' + line.trim();
  }
  return notes.map(n => {
    const en = n.match(/(?:^|\n)EN:\s*([\s\S]*?)(?=\nES:|$)/);
    const es = n.match(/(?:^|\n)ES:\s*([\s\S]*)$/);
    if (!en && !es) return [n.replace(/\n/g, ' '), n.replace(/\n/g, ' ')];
    if (!en || !es) fail(file, `a note needs both "EN:" and "ES:" lines: "${n.slice(0, 60)}…"`);
    return [en[1].replace(/\n/g, ' ').trim(), es[1].replace(/\n/g, ' ').trim()];
  });
}

function parseTable(lines) {
  const rows = lines.filter(l => /^\s*\|/.test(l)).map(l => l.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim()));
  const head = rows[0];
  const body = rows.slice(1).filter(r => !r.every(c => /^:?-{2,}:?$/.test(c)));
  const cell = (c, tag) => {
    const parts = c.split(' // ');
    let html = parts.length > 1 ? L(inline(parts[0]), inline(parts[1])) : inline(c);
    html = html.replace(/\[\[(\w+)\]\]/g, (_, b) => `<span class="origin o-${b.toLowerCase()}">${b}</span>`);
    return `<${tag}${tag === 'td' && parts.length > 1 ? ' class="txt"' : ''}>${html}</${tag}>`;
  };
  return `<table class="map-table"><thead><tr>${head.map(c => cell(c, 'th')).join('')}</tr></thead>`
    + `<tbody>${body.map(r => `<tr>${r.map(c => cell(c, 'td')).join('')}</tr>`).join('')}</tbody></table>`;
}

function parseCode(text, file) {
  if (!text || !text.trim()) return null;
  const lines = text.split('\n');
  const intro = { en: [], es: [] };
  const files = [];
  let cur = null, target = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const h = line.match(/^##\s+(.+?)\s*$/);
    if (h) { const [en, es] = bi(h[1]); cur = { tabEn: en, tabEs: es, obj: '', code: null, lang: 'abap', table: null, rest: [] }; files.push(cur); continue; }
    if (!cur) {
      const m = line.match(/^(EN|ES):\s*(.*)$/);
      if (m) { target = m[1].toLowerCase(); intro[target].push(m[2]); }
      else if (line.trim() && target) intro[target].push(line.trim());
      continue;
    }
    const fence = line.match(/^```\s*([\w-]*)\s*$/);
    if (fence && cur.code === null) {
      const body = [];
      for (i++; i < lines.length && !/^```\s*$/.test(lines[i]); i++) body.push(lines[i]);
      if (i >= lines.length) fail(file, `a code block in "## ${cur.tabEn}" is not closed with \`\`\``);
      cur.code = body;
      cur.lang = (fence[1] || 'abap').toLowerCase();
      continue;
    }
    if (/^\s*\|/.test(line) && cur.code === null) {
      const t = [];
      while (i < lines.length && /^\s*\|/.test(lines[i])) t.push(lines[i++]);
      i--;
      cur.table = parseTable(t);
      continue;
    }
    const obj = line.match(/^\s*`([^`]+)`\s*$/);
    if (obj && !cur.obj && cur.code === null && !cur.table) { cur.obj = obj[1]; continue; }
    cur.rest.push(line);
  }
  if (!files.length) fail(file, 'the "# Code" section needs at least one "## Tab name" with a code block or a table');
  if (!intro.en.length || !intro.es.length) fail(file, 'the "# Code" section needs an "EN:" and an "ES:" introduction');
  for (const f of files) {
    if (!f.code && !f.table) fail(file, `"## ${f.tabEn}" has no code block (\`\`\`abap … \`\`\`) and no table`);
    f.notes = parseNotes(f.rest, file);
    if (f.code) {
      f.marks = {};
      f.code = f.code.map((l, k) => {
        const m = l.match(MARK);
        if (!m) return l.replace(/\s+$/, '');
        const n = +(m[1] || m[2]);
        (f.marks[n] = f.marks[n] || []).push(k + 1);
        return l.replace(MARK, '');
      });
      for (const n of Object.keys(f.marks)) if (n > f.notes.length) fail(file, `line marker //${n} in "## ${f.tabEn}" has no note ${n}`);
    }
  }
  return { intro: { en: intro.en.join(' '), es: intro.es.join(' ') }, files };
}

// [3, 8, 9, 10, 14] → "3,8-10,14"
function ranges(lines) {
  const out = [];
  for (const n of lines) {
    const last = out[out.length - 1];
    if (last && n === last[1] + 1) last[1] = n; else out.push([n, n]);
  }
  return out.map(([a, b]) => (a === b ? `${a}` : `${a}-${b}`)).join(',');
}

function renderCode(code) {
  const notes = [];
  const figs = code.files.map((f, idx) => {
    const body = f.table
      ? `<div class="map-wrap">${f.table}</div>`
      : `<pre class="code-block" data-code${f.lang !== 'abap' ? ` data-lang="${attr(f.lang)}"` : ''}>${esc(f.code.join('\n'))}</pre>`;
    if (f.notes.length) {
      notes.push(`          <ol class="code-notes" data-for="${idx}">\n` + f.notes.map(([en, es], k) => {
        const r = f.marks && f.marks[k + 1];
        const line = r ? ` data-line="${ranges(r)}"` : '';
        return `            <li${line}>${L(inline(en), inline(es))}</li>`;
      }).join('\n') + '\n          </ol>');
    }
    return `            <figure class="code-file" data-tab-en="${attr(f.tabEn)}" data-tab-es="${attr(f.tabEs)}">\n`
      + (f.obj ? `              <figcaption class="code-obj">${esc(f.obj)}</figcaption>\n` : '')
      + `              ${body}\n            </figure>`;
  });
  return `        <div class="code-panel">
          <div class="code-head">
            <h4><svg class="i"><use href="#i-code"/></svg>${L('The code that matters', 'El código que importa')}</h4>
            <small>${L('Simplified, anonymised excerpt', 'Extracto simplificado y anonimizado')}</small>
          </div>
          <p lang="en">${inline(code.intro.en)}</p>
          <p lang="es">${inline(code.intro.es)}</p>
          <div class="code-window">
            <div class="code-bar"><span class="dots" aria-hidden="true"><i></i><i></i><i></i></span><div class="code-tabs" role="tablist"></div><button type="button" class="btn small code-copy"><svg class="i"><use href="#i-copy"/></svg><span class="btn-label">${L('Copy', 'Copiar')}</span></button></div>
${figs.join('\n')}
          </div>
${notes.join('\n')}
        </div>`;
}

/* ---------------------------------------------------------------- one project */
function readProject(path, icons) {
  const file = basename(path);
  const { meta, body } = frontMatter(readFileSync(path, 'utf8'), file);
  if (/^(true|yes|sí|si)$/i.test(meta.draft || '')) return null;
  for (const k of ['id', 'place', 'icon', 'kicker', 'title']) if (!meta[k]) fail(file, `"${k}:" is missing in the --- block`);
  if (!/^[a-z0-9-]+$/.test(meta.id)) fail(file, `id "${meta.id}" can only use lower-case letters, digits and "-"`);
  if (!['main', 'more'].includes(meta.place)) fail(file, `place must be "main" (front page) or "more" ("More projects"), not "${meta.place}"`);
  if (meta.place === 'main' && !CATEGORIES.includes(meta.category)) fail(file, `category must be one of: ${CATEGORIES.join(', ')}`);
  const icon = meta.icon.replace(/^#?i-/, '');
  if (!icons.has(icon)) fail(file, `icon "${icon}" does not exist. Available: ${[...icons].sort().join(', ')}`);
  const top = topSections(body, file);
  const en = story(top.en, file, 'en');
  const es = story(top.es, file, 'es');
  if (!en.summary || !es.summary) fail(file, 'each language needs a "> " summary line right after its # heading (it is the text on the card)');
  return {
    file, meta, icon, en, es,
    order: Number(meta.order ?? 999),
    code: parseCode(top.code, file),
    tags: (Array.isArray(meta.tags) ? meta.tags : meta.tags ? meta.tags.split(/\s*,\s*/) : []).map(bi),
  };
}

// Indent generated HTML for readability, but never inside <pre> (that would change the code)
function indent(s, n) {
  let inPre = false;
  return s.split('\n').map(l => {
    const out = inPre || !l.trim() ? l : ' '.repeat(n) + l;
    if (/<pre[\s>]/.test(l) && !/<\/pre>/.test(l)) inPre = true;
    else if (inPre && /<\/pre>/.test(l)) inPre = false;
    return out;
  }).join('\n');
}

function renderParts(p) {
  const [en1, en2] = renderStory(p.en.sections);
  const [es1, es2] = renderStory(p.es.sections);
  let html = `          <div lang="en">\n${indent(en1, 12)}\n          </div>\n          <div lang="es">\n${indent(es1, 12)}\n          </div>`;
  if (p.code) html += '\n' + renderCode(p.code);
  if (en2 || es2) html += `\n          <div lang="en">\n${indent(en2, 12)}\n          </div>\n          <div lang="es">\n${indent(es2, 12)}\n          </div>`;
  return html;
}

function renderFlow(v) {
  if (!v) return '';
  const arrows = v.includes('->');
  const steps = v.split(arrows ? /\s*->\s*/ : /\s*;\s*/).filter(Boolean).map(s => { const [a, b] = bi(s); return `<span>${a === b ? inline(a) : L(inline(a), inline(b))}</span>`; });
  return `\n        <div class="front-flow" aria-hidden="true">${steps.join(arrows ? '<i>→</i>' : '')}</div>`;
}

function renderMain(p) {
  const m = p.meta;
  const [kEn, kEs] = bi(m.kicker);
  const [tEn, tEs] = bi(m.title);
  const tags = p.tags.map(([a, b]) => `<span class="tag">${a === b ? inline(a) : L(inline(a), inline(b))}</span>`).join('');
  const status = m.status ? (([a, b]) => `<span class="status">${L(inline(a), inline(b))}</span>`)(bi(m.status)) : '';
  const chip = p.code ? '<span class="code-chip" title="Includes ABAP code" data-es-title="Incluye código ABAP"><svg class="i"><use href="#i-code"/></svg>ABAP</span>' : '';
  return `      <!-- ${p.file} -->
      <article class="card glass${/^wide$/i.test(m.size || '') ? ' span2' : ''}" tabindex="0" role="button" aria-haspopup="dialog" data-id="${attr(m.id)}" data-cat="${attr(m.category)}" data-kicker="${attr(kEn)}" data-kicker-es="${attr(kEs)}">
        <div class="card-top"><span class="tile"><svg class="i"><use href="#i-${p.icon}"/></svg></span>${chip}<span class="plus"><svg class="i"><use href="#i-plus"/></svg></span></div>
        <h3>${L(inline(tEn), inline(tEs))}</h3>
        <p lang="en">${inline(p.en.summary)}</p>
        <p lang="es">${inline(p.es.summary)}</p>${renderFlow(m.flow)}
        <div class="tags">${tags}${status}</div>
        <template class="detail">
${renderParts(p)}
        </template>
      </article>`;
}

function renderMoreItem(p) {
  const m = p.meta;
  const status = m.status ? (([a, b]) => `<span class="status">${L(inline(a), inline(b))}</span>`)(bi(m.status)) : '';
  return `          <details class="more-item" data-id="${attr(m.id)}">
            <summary>
              <span class="mi-tile"><svg class="i"><use href="#i-${p.icon}"/></svg></span>
              <span class="mi-text"><span class="mi-kicker">${L(...bi(m.kicker).map(inline))}${status}</span><span class="mi-title">${L(...bi(m.title).map(inline))}</span><span class="mi-sub">${L(inline(p.en.summary), inline(p.es.summary))}</span></span>
              <span class="mi-chev" aria-hidden="true"><svg class="i"><use href="#i-plus"/></svg></span>
            </summary>
            <div class="mi-body">
${indent(renderParts(p), 4)}
            </div>
          </details>`;
}

